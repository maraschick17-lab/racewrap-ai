const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe',args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,acceptDownloads:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base=process.env.BASE_URL||'https://racewrap-ai-studio.onrender.com';
  await page.goto(base+'/?test=layouts&nocache='+Date.now(),{waitUntil:'domcontentloaded',timeout:60000});
  const asset=await page.locator('script[src*="studio-v3.js"]').getAttribute('src');
  if(!/^studio-v3\.js\?v=[a-z0-9-]+$/i.test(asset))throw Error('Missing active versioned JS asset '+asset);
  const svg='<svg xmlns="http://www.w3.org/2000/svg" width="800" height="400"><rect width="800" height="400" fill="white"/><rect x="50" y="50" width="700" height="300" fill="#ddd"/></svg>';
  await page.locator('#template').setInputFiles({name:'licensed-test-grid.svg',mimeType:'image/svg+xml',buffer:Buffer.from(svg)});
  await page.waitForFunction(()=>document.querySelector('#sourceMeta').textContent.includes('licensed-test-grid.svg'));
  if(await page.locator('#layoutRebase').isDisabled())throw Error('Manual baseline not enabled after template import');
  await page.locator('#layoutRebase').click();
  if(await page.locator('#layout1').isDisabled())throw Error('Manual layout comparisons unavailable');
  await page.locator('#prompt').fill('Red silver number 17 lightning');
  await page.locator('#generate').click();
  await page.waitForFunction(()=>!document.querySelector('#generate').disabled && /design applied/i.test(document.querySelector('#status').textContent));
  const get=()=>page.evaluate(()=>Object.fromEntries(['pattern','patternAngle','patternScale','patternOpacity','patternX','patternY'].map(id=>[id,document.getElementById(id).value])));
  const original=await get();
  await page.locator('#layout1').click();const flowing=await get();
  if(flowing.pattern===original.pattern&&flowing.patternAngle===original.patternAngle)throw Error('Flowing layout unchanged');
  await page.locator('#layout2').click();const compact=await get();
  if(compact.pattern===flowing.pattern)throw Error('Compact layout unchanged');
  await page.locator('#layout0').click();const restored=await get();
  if(JSON.stringify(restored)!==JSON.stringify(original))throw Error('Original layout not restored');
  await page.locator('#layout1').click();
  const downloadPromise=page.waitForEvent('download');await page.locator('#saveProject').click();const download=await downloadPromise;
  const path=await download.path();const fs=require('fs');const json=JSON.parse(fs.readFileSync(path,'utf8'));
  if(json.layoutComparison.choice!==1)throw Error('Layout choice not persisted');
  await page.locator('#openProject').setInputFiles({name:'restore.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(json))});
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('restored'));
  const after=await get();if(JSON.stringify(after)!==JSON.stringify(flowing))throw Error('Restored project layout mismatch');
  if(await page.locator('#layout1').getAttribute('aria-pressed')!=='true')throw Error('Selected layout not restored');
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  if(overflow)throw Error('390px mobile horizontal overflow');
  if(errors.length)throw Error('Browser errors: '+errors.join(';'));
  console.log('PASS: layout variants, reversibility, JSON roundtrip, 390px touch viewport, zero JS errors; asset='+asset);
  await browser.close();
})().catch(e=>{console.error('FAIL:',e.stack||e);process.exit(1);});
